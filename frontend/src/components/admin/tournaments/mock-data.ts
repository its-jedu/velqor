function make(
  id: string,
  status: TournamentStatus,
  joined: number,
  overrides: Partial<TournamentInput>
): Tournament {
  return {
    ...defaultTournamentInput(),
    ...overrides,
    id,
    status,
    joined_players: joined,
    created_at: "2026-10-25T10:00:00.000Z",
  }
}

